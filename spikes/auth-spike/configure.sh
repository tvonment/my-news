#!/bin/sh
# Writes Generated/TenantIDs.swift, the tenant and application ids the spike signs in
# with. The file is git-ignored: the repository is public, and docs/identity.md keeps
# tenant, application and object ids out of it (they live in the azd env).
#
# Each value comes from the environment first, then from the azd env, read one key at
# a time with `azd env get-value` (as scripts/get_token.py does), so MYNEWS_HMAC_KEY is
# never read. Rerun after the ids change, then `xcodegen generate` if the project is
# missing the file.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
out="$here/Generated/TenantIDs.swift"

value() {
    eval "v=\${$1:-}"
    if [ -z "$v" ] && command -v azd >/dev/null 2>&1; then
        v=$(azd env get-value "$1" --cwd "$repo" --no-prompt 2>/dev/null || true)
    fi
    if ! printf '%s' "$v" | grep -Eqx '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'; then
        echo "configure.sh: $1 is missing or not a lower-case GUID. Set it in the environment or in the azd env (azd env set $1 <value>)." >&2
        exit 1
    fi
    printf '%s' "$v"
}

tenant_id=$(value ENTRA_TENANT_ID)
ios_client_id=$(value MYNEWS_IOS_CLIENT_ID)
api_client_id=$(value ENTRA_API_CLIENT_ID)

mkdir -p "$here/Generated"
tmp="$out.tmp.$$"
cat >"$tmp" <<EOF
// Generated by configure.sh from the azd env. Git-ignored on purpose: the repository
// is public and keeps tenant and application ids out (docs/identity.md).

nonisolated enum TenantIDs {
    /// ENTRA_TENANT_ID: the External ID tenant "von Mentlen News".
    static let tenantID = "$tenant_id"
    /// MYNEWS_IOS_CLIENT_ID: the mynews-ios registration (public client).
    static let iosClientID = "$ios_client_id"
    /// ENTRA_API_CLIENT_ID: mynews-api, whose access_as_user scope the spike requests.
    static let apiClientID = "$api_client_id"
}
EOF
mv "$tmp" "$out"
echo "Wrote ${out#"$repo"/} (ENTRA_TENANT_ID, MYNEWS_IOS_CLIENT_ID, ENTRA_API_CLIENT_ID)."
